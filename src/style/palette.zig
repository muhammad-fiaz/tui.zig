//! Perceptual OKLCH color palette scales (`c50`..`c950`) and gradient helpers built over `tint`.

const std = @import("std");
const tint = @import("tint");
const color_mod = @import("color.zig");
const testing = std.testing;

pub const Color = color_mod.Color;
pub const Rgb = color_mod.Rgb;

/// Re-exports `tint.palette` curves and ramps cleanly.
pub const raw = tint.palette;

/// Fills `out` with a smooth gradient interpolating across `stops` (`Color` values).
pub fn gradientColors(out: []Color, stops: []const Color) void {
    if (out.len == 0 or stops.len == 0) return;
    var rgb_stops_stack: [16]Rgb = undefined;
    const n = @min(stops.len, rgb_stops_stack.len);
    for (0..n) |i| {
        const tc = stops[i].toTint() orelse Color.rgb(255, 255, 255).toTint().?;
        rgb_stops_stack[i] = tc.toRgb();
    }
    var rgb_out_stack: [256]Rgb = undefined;
    const chunk = @min(out.len, rgb_out_stack.len);
    tint.palette.gradient(rgb_out_stack[0..chunk], rgb_stops_stack[0..n]);
    for (0..chunk) |i| {
        out[i] = Color.rgb(rgb_out_stack[i].r, rgb_out_stack[i].g, rgb_out_stack[i].b);
    }
}

/// Complete shade stop scale (`c50`..`c950`) for perceptual OKLCH color palettes.
pub const Scale = struct {
    c50: Color,
    c100: Color,
    c200: Color,
    c300: Color,
    c400: Color,
    c500: Color,
    c600: Color,
    c700: Color,
    c800: Color,
    c900: Color,
    c950: Color,
};

fn oklchStop(l_pct: f64, c: f64, h: f64) Color {
    return Color.oklch(l_pct / 100.0, c, h);
}

fn oklchScale(comptime stops: [11][3]f64) Scale {
    @setEvalBranchQuota(200000);
    return comptime .{
        .c50 = oklchStop(stops[0][0], stops[0][1], stops[0][2]),
        .c100 = oklchStop(stops[1][0], stops[1][1], stops[1][2]),
        .c200 = oklchStop(stops[2][0], stops[2][1], stops[2][2]),
        .c300 = oklchStop(stops[3][0], stops[3][1], stops[3][2]),
        .c400 = oklchStop(stops[4][0], stops[4][1], stops[4][2]),
        .c500 = oklchStop(stops[5][0], stops[5][1], stops[5][2]),
        .c600 = oklchStop(stops[6][0], stops[6][1], stops[6][2]),
        .c700 = oklchStop(stops[7][0], stops[7][1], stops[7][2]),
        .c800 = oklchStop(stops[8][0], stops[8][1], stops[8][2]),
        .c900 = oklchStop(stops[9][0], stops[9][1], stops[9][2]),
        .c950 = oklchStop(stops[10][0], stops[10][1], stops[10][2]),
    };
}

