test "oklch palette scales and gradients resolve true colors" {
    const sky400 = sky.c400.toRgb().?;
    try testing.expect(sky400.b > sky400.g and sky400.g > sky400.r);
    try testing.expect(lime.c400.toRgb().?.g > 200);
    try testing.expect(fuchsia.c500.toRgb().?.r > 180);
    try testing.expect(stone.c950.luminance().? < stone.c50.luminance().?);
    try testing.expect(mauve.c500.toRgb() != null);
    try testing.expect(olive.c500.toRgb() != null);
    try testing.expect(mist.c500.toRgb() != null);
    try testing.expect(taupe.c500.toRgb() != null);

    var ramp_buf: [5]Color = undefined;
    gradientColors(&ramp_buf, &.{ red.c500, blue.c500 });
    try testing.expectEqual(red.c500.toRgb().?, ramp_buf[0].toRgb().?);
    try testing.expectEqual(blue.c500.toRgb().?, ramp_buf[4].toRgb().?);
}
